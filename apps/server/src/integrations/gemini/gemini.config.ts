import { GoogleGenAI } from '@google/genai';
import { env } from '../../config/env';
import { logger } from '../../utils/logger';

export interface GeminiConfigOptions {
  apiKey?: string;
  defaultModel?: string;
}

export const FALLBACK_MODELS = [
  env.GEMINI_MODEL || 'gemini-3.5-flash-lite',
  'gemini-3.5-flash-lite',
  'gemini-3.1-flash-lite',
  'gemini-3-flash-preview',
  'gemini-3.5-flash',
];

/**
 * Gemini Provider Client Manager
 * Handles lazy initialization, multi-model fallback, and health checks for Google Gemini AI.
 */
export class GeminiProvider {
  private static instance: GoogleGenAI | null = null;
  private static modelName: string = env.GEMINI_MODEL || 'gemini-3.5-flash-lite';

  /**
   * Lazily retrieve the Gemini client instance
   */
  public static getClient(): GoogleGenAI {
    if (!GeminiProvider.instance) {
      const apiKey = env.GEMINI_API_KEY;

      if (!apiKey) {
        logger.warn(
          'GEMINI_API_KEY is not configured in server environment. Gemini operations will fail until key is supplied.',
        );
      }

      GeminiProvider.instance = new GoogleGenAI({
        apiKey: apiKey || 'unconfigured',
      });
      logger.info('Gemini provider initialized.');
    }

    return GeminiProvider.instance;
  }

  /**
   * Check if Gemini API key is configured
   */
  public static isConfigured(): boolean {
    return Boolean(env.GEMINI_API_KEY && env.GEMINI_API_KEY.trim().length > 0);
  }

  /**
   * Default configured model name
   */
  public static get defaultModel(): string {
    return GeminiProvider.modelName;
  }

  /**
   * Get unique ordered list of fallback models
   */
  public static get candidateModels(): string[] {
    const primary = env.GEMINI_MODEL || 'gemini-3.5-flash-lite';
    const set = new Set<string>([primary, ...FALLBACK_MODELS]);
    return Array.from(set);
  }

  /**
   * Execute generateContent with intelligent multi-model fallback
   */
  public static async generateWithFallback(params: {
    contents: any;
    config?: any;
    timeoutMs?: number;
  }): Promise<{ text: string; modelUsed: string; usage?: any }> {
    const client = GeminiProvider.getClient();
    const candidates = GeminiProvider.candidateModels;
    const timeoutMs = params.timeoutMs || 25000;

    let lastError: any = null;

    for (const model of candidates) {
      try {
        const timeoutPromise = new Promise<never>((_, reject) =>
          setTimeout(() => reject(new Error(`Timeout after ${timeoutMs}ms on model ${model}`)), timeoutMs),
        );

        const responsePromise = client.models.generateContent({
          model,
          contents: params.contents,
          config: params.config,
        });

        const response = await Promise.race([responsePromise, timeoutPromise]);
        const text = response.text || '';

        if (!text.trim()) {
          throw new Error(`Empty response generated by model ${model}`);
        }

        return {
          text: text.trim(),
          modelUsed: model,
          usage: response.usageMetadata,
        };
      } catch (err: any) {
        lastError = err;
        const status = err?.status || err?.code;
        const msg = err?.message || String(err);
        logger.warn(
          `Gemini model "${model}" failed (status: ${status}): ${msg.slice(0, 120)}. Trying fallback candidate...`,
        );

        // If error is unauthorized (invalid API key), no model will work; throw immediately
        if (status === 401 || status === 403) {
          throw err;
        }
      }
    }

    // All candidates failed
    throw lastError || new Error('All Gemini candidate models failed to generate content');
  }

  /**
   * Check live health status of Gemini
   */
  public static async checkHealth(): Promise<{
    isOnline: boolean;
    model: string;
    latencyMs?: number;
    error?: string;
  }> {
    if (!GeminiProvider.isConfigured()) {
      return { isOnline: false, model: 'unconfigured', error: 'API key not configured' };
    }

    try {
      const start = Date.now();
      const res = await GeminiProvider.generateWithFallback({
        contents: 'ping',
        config: { maxOutputTokens: 5 },
        timeoutMs: 6000,
      });
      return {
        isOnline: true,
        model: res.modelUsed,
        latencyMs: Date.now() - start,
      };
    } catch (err: any) {
      return {
        isOnline: false,
        model: env.GEMINI_MODEL || 'gemini-3.5-flash-lite',
        error: err?.message || 'Health check failed',
      };
    }
  }
}
